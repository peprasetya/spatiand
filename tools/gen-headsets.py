#!/usr/bin/env python3
"""The headsets the device table knows, for the shells that are not Rust.

crates/spatiand-hmd/src/devices.toml is the one place a headset is described. The Rust core
reads it at build time; the Mac's shell (Swift) and the Beam Pro's (Java) need two things from
it before the core has opened anything -- whether a USB device that has just arrived is a
headset, and (the Mac) which of its screens is the headset's -- and get them here, as generated
files that are committed, so that no build needs Python:

    mac/Sources/Spatiand/Headsets.swift
    android/src/id/prasetya/spatiand/Headsets.java
    android/res/xml/glasses.xml      (the USB devices that open Spatiand when plugged in)

    tools/gen-headsets.py

Run after changing the table; spatiand-hmd's test `generated_shell_tables_match` fails until it
has been.
"""

import os
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "crates/spatiand-hmd/src/devices.toml")
SWIFT = os.path.join(ROOT, "mac/Sources/Spatiand/Headsets.swift")
JAVA = os.path.join(ROOT, "android/src/id/prasetya/spatiand/Headsets.java")
XML = os.path.join(ROOT, "android/res/xml/glasses.xml")

HEADER = "Generated by tools/gen-headsets.py from crates/spatiand-hmd/src/devices.toml: do not edit."


def main():
    devices = tomllib.load(open(TABLE, "rb"))["device"]

    usb = "\n".join(
        f'        (vendor: 0x{d["vid"]:04x}, product: 0x{d["pid"]:04x}, name: "{d["name"]}"),' for d in devices
    )
    displays = "\n".join(
        f'        (vendor: 0x{d["edid"][0]:04x}, product: 0x{d["edid"][1]:04x}, name: "{d["name"]}"),'
        for d in devices
        if "edid" in d
    )
    open(SWIFT, "w").write(f"""//  Headsets.swift -- {HEADER}
//
//  The headsets Spatiand knows, as the Mac's shell needs them before the core has opened one:
//  their USB identity (is what was just plugged in a headset?) and their display's EDID (which
//  screen is the headset's?).

enum Headsets {{
    /// Every headset the table knows, by its USB vendor and product.
    static let usb: [(vendor: Int, product: Int, name: String)] = [
{usb}
    ]

    /// Every headset whose display the table knows, by its EDID manufacturer ID and product
    /// code (CGDisplayVendorNumber, CGDisplayModelNumber).
    static let displays: [(vendor: UInt32, product: UInt32, name: String)] = [
{displays}
    ]

    static func isHeadset(vendor: Int, product: Int) -> Bool {{
        usb.contains {{ $0.vendor == vendor && $0.product == product }}
    }}

    static func isHeadsetDisplay(vendor: UInt32, product: UInt32) -> Bool {{
        displays.contains {{ $0.vendor == vendor && $0.product == product }}
    }}
}}
""")

    rows = "\n".join(f'        {{0x{d["vid"]:04x}, 0x{d["pid"]:04x}}}, // {d["name"]}' for d in devices)
    open(JAVA, "w").write(f"""// {HEADER}
package id.prasetya.spatiand;

/**
 * The headsets Spatiand knows, as the Beam Pro's shell needs them before the core has opened
 * one: is a USB device that has just arrived a headset?
 */
final class Headsets {{
    /** USB vendor and product of every headset the table knows. */
    static final int[][] USB = {{
{rows}
    }};

    static boolean known(int vendor, int product) {{
        for (int[] row : USB) {{
            if (row[0] == vendor && row[1] == product) return true;
        }}
        return false;
    }}

    private Headsets() {{}}
}}
""")
    filters = "\n".join(
        f'    <!-- {d["name"]}: vendor 0x{d["vid"]:04x}, product 0x{d["pid"]:04x} -->\n'
        f'    <usb-device vendor-id="{d["vid"]}" product-id="{d["pid"]}" />'
        for d in devices
    )
    open(XML, "w").write(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {HEADER} -->
<resources>
{filters}
</resources>
""")
    print(f"wrote Headsets.swift, Headsets.java and glasses.xml: {len(devices)} headsets")


if __name__ == "__main__":
    main()
